const cache = new Map();
// nome normalizzato + le parole italiane corrispondenti (solo se ce ne sono)
export function itName(name) {
  const n = norm(name || '');
  let out = cache.get(n);
  if (out === undefined) {
    const t = n.replace(/[^a-z0-9 ]/g, ' ');
    const add = [];
    for (const [re, it] of DICT) if (re.test(t)) add.push(it);
    out = add.length ? `${n} ${add.join(' ')}` : n;
    cache.set(n, out);
  }
  return out;
}
